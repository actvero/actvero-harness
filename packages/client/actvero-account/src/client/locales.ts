export function errorKey(code: string): CopyKey {
  if (code.startsWith('storage_')) return 'storage'
  if (['network_unavailable', 'identity_unavailable', 'http_429'].includes(code)) return 'network'
  if (['device_revoked', 'account_unavailable', 'invalid_identity'].includes(code)) return 'revoked'
  if (['session_expired', 'refresh_recovery_expired', 'login_expired'].includes(code)) return 'expired'
  if (code === 'reauthentication_required') return 'authenticate'
  if (['unsupported_contract', 'invalid_response', 'untrusted_authorization'].includes(code)) return 'incompatible'
  if (code === 'refresh_replayed') return 'recoveryConflict'
  if (code === 'logout_pending') return 'logoutPending'
  return 'failed'
}
