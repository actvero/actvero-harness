/** Generate only the checked-in desktop contract; never read a sibling checkout. */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { createHash } from 'node:crypto'
interface Schema {
  $ref?: string
  type?: string
  const?: unknown
  enum?: unknown[]
  anyOf?: Schema[]
  items?: Schema
  properties?: Record<string, Schema>
  required?: string[]
  additionalProperties?: boolean | Schema
}
function literal(value: unknown): string {
  if (typeof value === 'string') return `'${value.replaceAll("'", "\\'")}'`
  return JSON.stringify(value)
}
function formatted(schema: Schema): string {
  const body = type(schema)
  if (body.startsWith('{ ')) return '{\n  ' + body.slice(2, -2).split('; ').join('\n  ') + '\n}'
  if (body.length > 90 && body.includes(' | ')) return '\n  | ' + body.split(' | ').join('\n  | ')
  return body
}
function type(schema: Schema): string {
  if (schema.$ref) return schema.$ref.split('/').at(-1) ?? 'unknown'
  if (schema.const !== undefined) return literal(schema.const)
  if (schema.enum) return schema.enum.map(value => literal(value)).join(' | ')
  if (schema.anyOf) return schema.anyOf.map(type).join(' | ')
  if (schema.type === 'string') return 'string'
  if (schema.type === 'integer' || schema.type === 'number') return 'number'
  if (schema.type === 'boolean') return 'boolean'
  if (schema.type === 'null') return 'null'
  if (schema.type === 'array') return `(${type(schema.items ?? {})})[]`
  if (schema.type === 'object') {
    if (!schema.properties) return 'Record<string, unknown>'
    return `{ ${Object.entries(schema.properties)
      .map(([name, value]) => `${name}${schema.required?.includes(name) ? '' : '?'}: ${type(value)}`)
      .join('; ')} }`
  }
  return 'unknown'
}
const root = resolve(import.meta.dirname, '..')
const source = readFileSync(resolve(root, 'actvero/contracts/desktop-openapi.json'), 'utf8')
const schemas = (JSON.parse(source) as { components: { schemas: Record<string, Schema> } }).components.schemas
const output =
  '// Generated by scripts/actvero-contract.ts. Do not edit.\n// Snapshot sha256: ' +
  createHash('sha256').update(source).digest('hex') +
  '\n' +
  Object.entries(schemas)
    .map(([name, schema]) => `/** Platform schema ${name}. */\nexport type ${name} = ${formatted(schema)}\n`)
    .join('')
const target = resolve(root, 'apps/desktop/src/actvero/platform.generated.ts')
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('ACTVERO desktop contract types are stale')
} else writeFileSync(target, output)
